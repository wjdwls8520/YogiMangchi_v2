CREATE TABLE guest_retry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES trading_account(id),
    request_key VARCHAR(100) NOT NULL,
    balance_before NUMERIC(38,18) NOT NULL,
    balance_after NUMERIC(38,18) NOT NULL CHECK (balance_after>=0),
    capital_adjustment NUMERIC(38,18) NOT NULL,
    canceled_order_count INTEGER NOT NULL CHECK (canceled_order_count>=0),
    closed_position_count INTEGER NOT NULL CHECK (closed_position_count>=0),
    reset_at TIMESTAMPTZ NOT NULL,
    UNIQUE(account_id,request_key),
    CHECK (capital_adjustment=balance_after-balance_before)
);
ALTER TABLE position DROP CONSTRAINT position_close_state;
ALTER TABLE position ADD CONSTRAINT position_close_state CHECK (
    (close_reason IS NULL AND (
      (status='OPEN' AND quantity>0 AND margin>0 AND entry_notional>0 AND closed_at IS NULL AND exit_price IS NULL AND merged_into_position_id IS NULL) OR
      (status IN ('CLOSED','LIQUIDATED') AND quantity=0 AND margin=0 AND entry_notional=0 AND closed_at IS NOT NULL AND exit_price IS NOT NULL AND exit_price>0 AND merged_into_position_id IS NULL) OR
      (status='MERGED' AND merged_into_position_id IS NOT NULL AND merged_into_position_id<>id))) OR
    (close_reason IS NOT NULL AND close_reason IN ('MEMBER_WITHDRAWAL','GUEST_RETRY') AND status='CLOSED'
      AND quantity=0 AND margin=0 AND entry_notional=0 AND reserved_close_quantity=0 AND closed_at IS NOT NULL
      AND exit_price IS NULL AND merged_into_position_id IS NULL));
