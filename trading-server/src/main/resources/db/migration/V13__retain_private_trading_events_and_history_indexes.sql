-- Durable account-private delivery. Financial state and event snapshot commit in the same transaction.
CREATE TABLE trading_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES trading_account(id),
    order_id BIGINT NOT NULL REFERENCES trading_order(id),
    order_status VARCHAR(16) NOT NULL CHECK (order_status IN ('PENDING','FILLED','CANCELED','REJECTED')),
    event_type VARCHAR(32) NOT NULL CHECK (event_type IN ('ORDER_PENDING','ORDER_FILLED','ORDER_CANCELED','ORDER_REJECTED','POSITION_LIQUIDATED')),
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload)='object'),
    occurred_at TIMESTAMPTZ NOT NULL,
    UNIQUE (order_id,order_status)
);
CREATE INDEX trading_event_account_replay_idx ON trading_event(account_id,id);
CREATE INDEX position_closed_history_idx ON position(account_id,closed_at DESC,id DESC)
    WHERE status IN ('CLOSED','LIQUIDATED');
CREATE INDEX order_position_history_idx ON trading_order(position_id) WHERE position_id IS NOT NULL;
CREATE INDEX position_merged_history_idx ON position(merged_into_position_id) WHERE merged_into_position_id IS NOT NULL;
