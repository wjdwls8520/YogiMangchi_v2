-- Every financial insert, including engine Fill paths, receives an explicit immutable round reference.
-- Callers already hold AccountLock. A trigger prevents a forgotten new writer bypassing ownership.
CREATE FUNCTION assign_member_round() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE rid BIGINT; guest BOOLEAN;
BEGIN
 IF TG_TABLE_NAME IN ('fill','trading_event') THEN
   SELECT round_id INTO rid FROM trading_order WHERE id=NEW.order_id;
 ELSE
   SELECT guest_account INTO guest FROM trading_account WHERE id=NEW.account_id;
   IF guest THEN rid:=NULL;
   ELSE
     SELECT id INTO rid FROM member_trading_round WHERE account_id=NEW.account_id AND status='ACTIVE';
     IF rid IS NULL THEN RAISE EXCEPTION 'Active member round required'; END IF;
   END IF;
 END IF;
 IF NEW.round_id IS NOT NULL AND NEW.round_id IS DISTINCT FROM rid THEN RAISE EXCEPTION 'Invalid financial round'; END IF;
 IF TG_TABLE_NAME='fill' AND rid IS NOT NULL AND NOT EXISTS(SELECT 1 FROM member_trading_round WHERE id=rid AND status='ACTIVE') THEN RAISE EXCEPTION 'Completed round cannot receive a new fill'; END IF;
 NEW.round_id:=rid;
 RETURN NEW;
END $$;
CREATE TRIGGER position_round BEFORE INSERT ON position FOR EACH ROW EXECUTE FUNCTION assign_member_round();
CREATE TRIGGER order_round BEFORE INSERT ON trading_order FOR EACH ROW EXECUTE FUNCTION assign_member_round();
CREATE TRIGGER fill_round BEFORE INSERT ON fill FOR EACH ROW EXECUTE FUNCTION assign_member_round();
CREATE TRIGGER event_round BEFORE INSERT ON trading_event FOR EACH ROW EXECUTE FUNCTION assign_member_round();
CREATE FUNCTION retain_financial_round() RETURNS trigger LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
 IF NEW.round_id IS DISTINCT FROM OLD.round_id THEN RAISE EXCEPTION 'Financial round is immutable'; END IF;
 IF TG_TABLE_NAME='trading_order' THEN
 IF NEW.status='FILLED' AND OLD.status<>'FILLED' AND NEW.round_id IS NOT NULL
    AND NOT EXISTS(SELECT 1 FROM member_trading_round WHERE id=NEW.round_id AND status='ACTIVE') THEN
    RAISE EXCEPTION 'Completed round cannot execute';
 END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER retain_position_round BEFORE UPDATE ON position FOR EACH ROW EXECUTE FUNCTION retain_financial_round();
CREATE TRIGGER retain_order_round BEFORE UPDATE ON trading_order FOR EACH ROW EXECUTE FUNCTION retain_financial_round();
CREATE TRIGGER retain_fill_round BEFORE UPDATE ON fill FOR EACH ROW EXECUTE FUNCTION retain_financial_round();
CREATE TRIGGER retain_event_round BEFORE UPDATE ON trading_event FOR EACH ROW EXECUTE FUNCTION retain_financial_round();
