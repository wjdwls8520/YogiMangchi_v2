CREATE FUNCTION retain_completed_round() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.status='COMPLETED' AND NEW IS DISTINCT FROM OLD THEN RAISE EXCEPTION 'Completed round is immutable'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER completed_round_immutable BEFORE UPDATE ON member_trading_round FOR EACH ROW EXECUTE FUNCTION retain_completed_round();

