CREATE TEMP TABLE hedge_merge ON COMMIT DROP AS
SELECT account_id,trading_symbol_id,side,min(id) survivor_id,
    sum(quantity) quantity,sum(initial_quantity) initial_quantity,sum(initial_margin) initial_margin,
    sum(quantity*entry_price) basis,sum(realized_pnl) realized_pnl,sum(reserved_close_quantity) reserved_close_quantity,min(opened_at) opened_at
FROM position WHERE status='OPEN' GROUP BY account_id,trading_symbol_id,side;

-- PostgreSQL numeric division chooses a result scale from significant digits. Widen BEFORE dividing,
-- and use the same HALF_EVEN display policy as Java (PostgreSQL round() uses ties away from zero).
CREATE FUNCTION pg_temp.hedge_average(basis NUMERIC, qty NUMERIC) RETURNS NUMERIC LANGUAGE plpgsql AS $$
DECLARE numerator NUMERIC; integral NUMERIC; remainder NUMERIC;
BEGIN
    numerator := basis * 1e18;
    integral := trunc(numerator::NUMERIC(140,70) / qty);
    remainder := numerator - integral * qty;
    IF remainder*2 > qty OR (remainder*2=qty AND mod(integral,2)=1) THEN integral := integral+1; END IF;
    RETURN integral * 0.000000000000000001;
END $$;

UPDATE trading_order o SET original_position_id=o.position_id,position_id=m.survivor_id
FROM position p JOIN hedge_merge m USING(account_id,trading_symbol_id,side)
WHERE o.position_id=p.id AND p.status='OPEN' AND o.action='CLOSE' AND o.status='PENDING' AND p.id<>m.survivor_id;

-- Donor rows remain immutable historical snapshots, explicitly excluded from active exposure and valuation.
UPDATE position p SET status='MERGED',merged_into_position_id=m.survivor_id
FROM hedge_merge m WHERE p.status='OPEN' AND p.account_id=m.account_id AND p.trading_symbol_id=m.trading_symbol_id
    AND p.side=m.side AND p.id<>m.survivor_id;
UPDATE position p SET quantity=m.quantity,initial_quantity=m.initial_quantity,initial_margin=m.initial_margin,
    entry_notional=m.basis,entry_price=pg_temp.hedge_average(m.basis,m.quantity),realized_pnl=m.realized_pnl,
    reserved_close_quantity=m.reserved_close_quantity,opened_at=m.opened_at,leverage=l.leverage,
    margin=ceil(m.basis::NUMERIC(100,60)*1e18/l.leverage)*0.000000000000000001
FROM hedge_merge m JOIN symbol_leverage l USING(account_id,trading_symbol_id) WHERE p.id=m.survivor_id;
UPDATE trading_order o SET leverage=l.leverage,reserved_margin=ceil((o.limit_price*o.quantity)::NUMERIC(100,60)*1e18/l.leverage)*0.000000000000000001
FROM symbol_leverage l WHERE o.account_id=l.account_id AND o.trading_symbol_id=l.trading_symbol_id
    AND o.status='PENDING' AND o.action='OPEN';
UPDATE wallet w SET used_margin=COALESCE((SELECT sum(p.margin) FROM position p WHERE p.account_id=w.account_id AND p.status='OPEN'),0),
    reserved_margin=COALESCE((SELECT sum(o.reserved_margin) FROM trading_order o WHERE o.account_id=w.account_id AND o.status='PENDING' AND o.action='OPEN'),0);

