-- Offline cutover: stop ALL old Trading instances/workers before migration; never run mixed versions.
-- Flyway's PostgreSQL transaction rolls back data and DDL together on any inconsistency.
LOCK TABLE trading_account, wallet, position, trading_order, fill IN ACCESS EXCLUSIVE MODE;

DO $$ BEGIN
    IF EXISTS (
        SELECT 1 FROM wallet w WHERE
          w.used_margin <> COALESCE((SELECT sum(p.margin) FROM position p WHERE p.account_id=w.account_id AND p.status='OPEN'),0)
          OR w.reserved_margin <> COALESCE((SELECT sum(o.reserved_margin) FROM trading_order o WHERE o.account_id=w.account_id AND o.status='PENDING' AND o.action='OPEN'),0)
    ) OR EXISTS (
        SELECT 1 FROM position p WHERE p.status='OPEN' AND NOT EXISTS (SELECT 1 FROM wallet w WHERE w.account_id=p.account_id)
    ) OR EXISTS (
        SELECT 1 FROM trading_order o WHERE o.status='PENDING' AND NOT EXISTS (SELECT 1 FROM wallet w WHERE w.account_id=o.account_id)
    ) OR EXISTS (
        SELECT 1 FROM position p WHERE p.status='OPEN' AND p.reserved_close_quantity <>
          COALESCE((SELECT sum(o.quantity) FROM trading_order o WHERE o.position_id=p.id AND o.status='PENDING' AND o.action='CLOSE'),0)
    ) OR EXISTS (
        SELECT 1 FROM trading_order o JOIN position p ON p.id=o.position_id WHERE o.status='PENDING' AND o.action='CLOSE'
          AND (p.status<>'OPEN' OR p.account_id<>o.account_id OR p.trading_symbol_id<>o.trading_symbol_id OR p.side<>o.side)
    ) THEN RAISE EXCEPTION 'Hedge migration: inconsistent wallet or CLOSE reservations; reconcile ledger before retry'; END IF;
    IF EXISTS (SELECT 1 FROM position WHERE status='OPEN' GROUP BY account_id,trading_symbol_id,side
        HAVING sum(quantity)>1000000000000 OR sum(quantity*entry_price)>1000000) THEN
        RAISE EXCEPTION 'Hedge migration: aggregate position exceeds supported quantity/notional; explicit risk reduction required';
    END IF;
END $$;

CREATE TABLE symbol_leverage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES trading_account(id) ON DELETE CASCADE,
    trading_symbol_id BIGINT NOT NULL REFERENCES trading_symbol(id),
    leverage INTEGER NOT NULL CHECK (leverage BETWEEN 1 AND 100),
    updated_at TIMESTAMPTZ NOT NULL,
    UNIQUE(account_id,trading_symbol_id)
);
-- Maximum of active/pending legacy leverage: shared by both sides, never requires extra migration cash.
INSERT INTO symbol_leverage(account_id,trading_symbol_id,leverage,updated_at)
SELECT account_id,trading_symbol_id,max(leverage),now() FROM (
    SELECT account_id,trading_symbol_id,leverage FROM position WHERE status='OPEN'
    UNION ALL
    SELECT account_id,trading_symbol_id,leverage FROM trading_order WHERE status='PENDING' AND action='OPEN'
) legacy GROUP BY account_id,trading_symbol_id;

