CREATE TABLE member_follow (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT NOT NULL REFERENCES member(id),
    following_id BIGINT NOT NULL REFERENCES member(id),
    active BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    deactivated_at TIMESTAMPTZ,
    CHECK (follower_id<>following_id),
    CHECK ((active AND deactivated_at IS NULL) OR (NOT active AND deactivated_at IS NOT NULL))
);
CREATE UNIQUE INDEX member_follow_active_pair ON member_follow(follower_id,following_id) WHERE active;
CREATE INDEX member_follow_followers ON member_follow(following_id,id DESC) WHERE active;
CREATE INDEX member_follow_followings ON member_follow(follower_id,id DESC) WHERE active;
