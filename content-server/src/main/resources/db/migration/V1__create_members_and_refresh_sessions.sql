CREATE TABLE member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(12) NOT NULL UNIQUE,
    profile_message VARCHAR(300) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','WITHDRAWN')),
    role VARCHAR(16) NOT NULL CHECK (role IN ('MEMBER','ADMIN')),
    terms_agreed_at TIMESTAMPTZ NOT NULL,
    privacy_agreed_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    withdrawn_at TIMESTAMPTZ
);
CREATE TABLE oauth_identity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    provider VARCHAR(16) NOT NULL CHECK (provider IN ('GOOGLE','KAKAO')),
    provider_subject VARCHAR(255) NOT NULL,
    email VARCHAR(320) NOT NULL,
    UNIQUE(provider,provider_subject)
);
CREATE TABLE refresh_session (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id UUID NOT NULL,
    member_id BIGINT NOT NULL REFERENCES member(id),
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','ROTATED','REVOKED')),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ
);
CREATE INDEX refresh_session_family_idx ON refresh_session(family_id);
CREATE INDEX refresh_session_member_idx ON refresh_session(member_id);
