CREATE TABLE community_post (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL REFERENCES member(id),
    category VARCHAR(24) NOT NULL CHECK (category IN ('MARKET','ANALYSIS','POSITION','FREE')),
    symbol_tag VARCHAR(24),
    title VARCHAR(120) NOT NULL,
    content TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DELETED')),
    like_count INTEGER NOT NULL DEFAULT 0 CHECK (like_count >= 0),
    comment_count INTEGER NOT NULL DEFAULT 0 CHECK (comment_count >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE INDEX community_post_latest_idx ON community_post(id DESC) WHERE status = 'ACTIVE';
CREATE INDEX community_post_category_latest_idx ON community_post(category, id DESC) WHERE status = 'ACTIVE';
CREATE INDEX community_post_popular_idx ON community_post(like_count DESC, id DESC) WHERE status = 'ACTIVE';

CREATE TABLE community_post_like (
    post_id BIGINT NOT NULL REFERENCES community_post(id),
    member_id BIGINT NOT NULL REFERENCES member(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (post_id, member_id)
);

CREATE TABLE community_comment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES community_post(id),
    member_id BIGINT NOT NULL REFERENCES member(id),
    parent_comment_id BIGINT REFERENCES community_comment(id),
    content VARCHAR(1000) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DELETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE INDEX community_comment_post_idx ON community_comment(post_id, id) WHERE status = 'ACTIVE';
